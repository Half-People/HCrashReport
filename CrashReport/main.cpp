HImage H_GUI::LoadTexture(const char* path)
{
    // Load from file
    HImage img;


    unsigned char* image_data = stbi_load(H_GUI::current_exe_path().append("\\").append(path).c_str(), &img.image_width, &img.image_height, &img.image_channel, 4);
    if (image_data == NULL)
        return img;

    // Create a OpenGL texture identifier
    GLuint image_texture;
    glGenTextures(1, &image_texture);
    glBindTexture(GL_TEXTURE_2D, image_texture);

    // Setup filtering parameters for display
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);

    // Upload pixels into texture
    glPixelStorei(GL_UNPACK_ROW_LENGTH, 0);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, img.image_width, img.image_height, 0, GL_RGBA, GL_UNSIGNED_BYTE, image_data);
    stbi_image_free(image_data);
    img.texture = (ImTextureID)(intptr_t)image_texture;
    return img;
}
void HImage::free_texture()
{
    if (texture != nullptr)
    {
        GLuint texture_buffer = (GLuint)texture;
        glDeleteTextures(1, &texture_buffer);
        texture = nullptr;
    }
}
