void SetWindowIcon(const char* path)
{
    // 使用 stb_image 加载图标
    int width, height, channels;
    unsigned char* img_data = stbi_load(path, &width, &height, &channels, 0);
    if (!img_data) {
        fprintf(stderr, "Could not load icon: %s\n", stbi_failure_reason());
        SDL_DestroyWindow(window);
        SDL_Quit();
        return ;
    }

    // 创建 SDL_Surface
    SDL_Surface* icon = SDL_CreateRGBSurfaceWithFormatFrom(
        img_data, width, height, 32, width * channels, SDL_PIXELFORMAT_RGBA32
    );

    if (!icon) {
        fprintf(stderr, "Could not create surface: %s\n", SDL_GetError());
        stbi_image_free(img_data);
        SDL_DestroyWindow(window);
        SDL_Quit();
        return ;
    }

    // 设置窗口图标
    SDL_SetWindowIcon(window, icon);

    // 释放图标图像
    SDL_FreeSurface(icon);
    stbi_image_free(img_data);
}

